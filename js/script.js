const grid = document.getElementById("tripGrid");
const modal = document.getElementById("tripModal");
const modalContent = document.getElementById("modalContent");

function tripCard(t){
  return `
    <article class="trip-card">
      <div class="trip-image" style="background-image:url('${t.image}')">
        <span class="trip-tag">${t.duration}</span>
      </div>
      <div class="trip-body">
        <h3>${t.name}</h3>
        <div class="trip-meta"><span>📍 ${t.pickup}</span><span>🗓 ${t.dates}</span></div>
        <div class="trip-price">${t.price} <small>onwards / package price</small></div>
        <div class="card-actions">
          <button class="btn btn-outline" onclick="openTrip('${t.id}')">View Itinerary</button>
          <a class="btn btn-primary" href="#booking" onclick="selectTrip('${t.name.replace(/'/g,"\\'")}')">Enquire</a>
        </div>
      </div>
    </article>`;
}
grid.innerHTML = trips.map(tripCard).join("");

function openTrip(id){
  const t = trips.find(x=>x.id===id);
  if(!t) return;
  modalContent.innerHTML = `
    <p class="eyebrow dark">${t.duration} • ${t.dates}</p>
    <h2 class="modal-title">${t.name}</h2>
    <p class="modal-sub">Pickup: ${t.pickup}</p>
    <div class="modal-price">${t.price}</div>
    ${t.note ? `<div class="booking-card" style="margin-bottom:20px"><strong>Note:</strong> ${t.note}</div>` : ""}
    <div class="itinerary">
      ${t.days.map(d=>`<div class="day"><h4>${d[0]}</h4><ul>${d[1].map(x=>`<li>${x}</li>`).join("")}</ul></div>`).join("")}
    </div>
    ${t.includes ? `<div class="modal-columns"><div><h4>Includes</h4><ul>${t.includes.map(x=>`<li>${x}</li>`).join("")}</ul></div><div><h4>Excludes</h4><ul>${t.excludes.map(x=>`<li>${x}</li>`).join("")}</ul></div></div>` : `<div class="booking-card" style="margin-top:25px"><strong>Package details:</strong> Detailed inclusions/exclusions are available on enquiry.</div>`}
    <div style="margin-top:28px;display:flex;gap:10px;flex-wrap:wrap">
      <a class="btn btn-primary" href="#booking" onclick="closeTrip();selectTrip('${t.name.replace(/'/g,"\\'")}')">Book / Enquire</a>
      <a class="btn btn-whatsapp" target="_blank" rel="noopener" href="https://wa.me/916353336828?text=${encodeURIComponent("Hi Surani Altitude Travel, I want to enquire about " + t.name + ".")}">WhatsApp</a>
    </div>`;
  modal.classList.add("open");
  modal.setAttribute("aria-hidden","false");
  document.body.style.overflow="hidden";
}
function closeTrip(){
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden","true");
  document.body.style.overflow="";
}
document.querySelectorAll("[data-close-modal]").forEach(el=>el.addEventListener("click",closeTrip));
document.addEventListener("keydown",e=>{if(e.key==="Escape")closeTrip()});

const select = document.getElementById("bookingTrip");
const wa = document.getElementById("whatsappButton");
function selectTrip(name){
  select.value = name;
  updateWhatsApp();
}
function updateWhatsApp(){
  const trip = select.value || "a trip";
  wa.href = "https://wa.me/916353336828?text=" + encodeURIComponent(`Hi Surani Altitude Travel, I want to enquire about ${trip}. Please share availability and booking details.`);
}
select.addEventListener("change",updateWhatsApp);
updateWhatsApp();

