// ===============================
// SECURITY / HTML
// ===============================

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}


// ===============================
// WHATSAPP
// ===============================

function whatsappLink(tripName) {

  const message =
    `Hi Surani Altitude Travel, I am interested in the ${tripName} trip. Please share availability, dates and booking details.`;

  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(message)}`;
}


// ===============================
// TRIP CARDS
// ===============================

function renderTrips() {

  if (!tripGrid) return;

  tripGrid.innerHTML = trips.map((trip, index) => `

    <article class="trip-card">

      <div class="trip-image">

        <img
          src="${trip.image}"
          alt="${escapeHtml(trip.name)}"
          loading="${index < 3 ? "eager" : "lazy"}"
          onerror="this.style.display='none'; this.parentElement.classList.add('image-missing');"
        >

        <span class="trip-badge">
          ${escapeHtml(trip.duration)}
        </span>

      </div>

      <div class="trip-body">

        <h3>
          ${escapeHtml(trip.name)}
        </h3>

        <p class="trip-meta">
          📍 ${escapeHtml(trip.pickup)}
        </p>

        <p class="trip-meta">
          🗓️ ${escapeHtml(trip.dates)}
        </p>

        <div class="trip-price">
          ${escapeHtml(trip.price)}
          <small>onwards / package price</small>
        </div>

        <div class="trip-actions">

          <button
            class="btn btn-outline"
            type="button"
            data-itinerary="${trip.id}"
          >
            View Itinerary
          </button>

          <a
            class="btn btn-primary"
            href="${whatsappLink(trip.name)}"
            target="_blank"
            rel="noopener"
          >
            Enquire
          </a>

        </div>

      </div>

    </article>

  `).join("");
}


// ===============================
// ITINERARY MODAL
// ===============================

function openModal(tripId) {

  const trip = trips.find(item => item.id === tripId);

  if (!trip || !modal || !modalContent) return;


  const dayHtml = trip.days.map(([title, points]) => `

    <div class="modal-day">

      <h4>
        ${escapeHtml(title)}
      </h4>

      <ul>

        ${points.map(point => `
          <li>
            ${escapeHtml(point)}
          </li>
        `).join("")}

      </ul>

    </div>

  `).join("");


  const includesHtml = trip.includes.length

    ? `
      <div class="modal-list">

        <h4>Includes</h4>

        <ul>
          ${trip.includes.map(item => `
            <li>${escapeHtml(item)}</li>
          `).join("")}
        </ul>

      </div>
    `

    : "";


  const excludesHtml = trip.excludes.length

    ? `
      <div class="modal-list">

        <h4>Excludes</h4>

        <ul>
          ${trip.excludes.map(item => `
            <li>${escapeHtml(item)}</li>
          `).join("")}
        </ul>

      </div>
    `

    : "";


  const noteHtml = trip.note

    ? `
      <p class="modal-note">
        ${escapeHtml(trip.note)}
      </p>
    `

    : "";


  modalContent.innerHTML = `

    <div class="modal-head">

      <p class="eyebrow dark">
        ${escapeHtml(trip.duration)}
      </p>

      <h2>
        ${escapeHtml(trip.name)}
      </h2>

      <p>
        ${escapeHtml(trip.pickup)}
        ·
        ${escapeHtml(trip.dates)}
      </p>

      <strong>
        ${escapeHtml(trip.price)}
      </strong>

    </div>


    <div class="modal-days">

      ${dayHtml}

    </div>


    <div class="modal-columns">

      ${includesHtml}

      ${excludesHtml}

    </div>


    ${noteHtml}


    <a
      class="btn btn-primary full"
      href="${whatsappLink(trip.name)}"
      target="_blank"
      rel="noopener"
    >
      Enquire on WhatsApp
    </a>

  `;


  modal.setAttribute("aria-hidden", "false");

  modal.classList.add("is-open");

  document.body.classList.add("modal-open");
}


// ===============================
// CLOSE MODAL
// ===============================

function closeModal() {

  if (!modal) return;

  modal.setAttribute("aria-hidden", "true");

  modal.classList.remove("is-open");

  document.body.classList.remove("modal-open");
}


// ===============================
// CLICK EVENTS
// ===============================

document.addEventListener("click", event => {

  const button = event.target.closest("[data-itinerary]");

  if (button) {

    openModal(button.dataset.itinerary);

  }


  if (event.target.closest("[data-close-modal]")) {

    closeModal();

  }

});


// ===============================
// ESCAPE KEY
// ===============================

document.addEventListener("keydown", event => {

  if (event.key === "Escape") {

    closeModal();

  }

});


// ===============================
// GOOGLE FORM
// ===============================

if (formButton) {

  formButton.href = GOOGLE_FORM_URL;

}


// ===============================
// WHATSAPP BOOKING
// ===============================

function updateWhatsApp() {

  if (!whatsappButton) return;

  const selectedTrip =
    bookingTrip?.value || "Custom Trip";

  const message =
    `Hi Surani Altitude Travel, I want to enquire about ${selectedTrip}. Please share details, dates, price and availability.`;

  whatsappButton.href =
    `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(message)}`;

}


if (bookingTrip) {

  bookingTrip.addEventListener(
    "change",
    updateWhatsApp
  );

}

updateWhatsApp();


// ===============================
// RENDER TRIPS
// ===============================

renderTrips();


// ===============================
// MOBILE MENU
// ===============================

const menuButton =
  document.querySelector(".menu-toggle");

const nav =
  document.querySelector(".site-nav");


if (menuButton && nav) {

  menuButton.addEventListener("click", () => {

    const expanded =
      menuButton.getAttribute("aria-expanded") === "true";

    menuButton.setAttribute(
      "aria-expanded",
      String(!expanded)
    );

    nav.classList.toggle("is-open");

  });


  nav.querySelectorAll("a").forEach(link => {

    link.addEventListener("click", () => {

      nav.classList.remove("is-open");

      menuButton.setAttribute(
        "aria-expanded",
        "false"
      );

    });

  });

}


